"""Pixel-art chess piece generator: 24x24 sprites, auto outline + auto shading.

Grid legend:
  .  transparent      #  body (auto-shaded light/mid/dark)
  l  forced light     d  forced dark        x  ink (outline color, eyes/lines)
  w  white (teeth / eye shine)              c  gold (crowns)
"""
